import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={Math,window:{},state:{entities:{enemies:[]}},player:{x:0,y:0,r:12},segmentDistance:(x,y,ax,ay,bx,by)=>{const dx=bx-ax,dy=by-ay,t=Math.max(0,Math.min(1,((x-ax)*dx+(y-ay)*dy)/(dx*dx+dy*dy||1)));return Math.hypot(x-ax-dx*t,y-ay-dy*t);}};
vm.createContext(context);vm.runInContext(fs.readFileSync('src/stage-physical-objects.js','utf8'),context);
const jaw={kind:'box',x:-92,y:4,hw:29,hh:79,a:0},bar={kind:'box',x:0,y:0,hw:120,hh:4,a:Math.PI/4};
assert(context.stageShapeCircleHit(jaw,-116,65,2),'visible outer jaw must receive damage');
assert(!context.stageShapeCircleHit(jaw,0,65,12),'central gate opening must stay empty');
assert(context.stageShapeSegmentHit(jaw,-280,65,140,65,3),'fast projectile must not tunnel through jaw');
assert(!context.stageShapeSegmentHit(jaw,-280,100,140,100,3),'projectile outside jaw must miss');
assert(context.stageShapeCircleHit(bar,70,70,3),'rotated thin structure must hit along its axis');
assert(!context.stageShapeCircleHit(bar,70,-70,3),'rotated structure must not use its enclosing circle');
assert(context.stageShapeSegmentHit(bar,-130,0,130,0,2),'swept crossing must hit rotated structure');
assert(!context.stageShapeSegmentHit(bar,-130,110,130,110,2),'distant swept crossing must miss');
const ordinary={x:0,y:0,r:16};
assert(context.enemyCircleOverlap(ordinary,20,0,5));assert(!context.enemyCircleOverlap(ordinary,23,0,5));
const multipart={x:0,y:0,r:155,stageBodyShapes:[jaw]};
assert(!context.enemyCircleOverlap(multipart,0,65,2));assert(context.enemySegmentOverlap(multipart,-280,65,140,65,3));
console.log('PASS 12 actual stage geometry regressions: outer parts, empty gaps, rotation, swept collision, ordinary enemy compatibility');

